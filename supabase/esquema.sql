-- ===== Productos =====
create table if not exists public.productos (
  id          bigint generated by default as identity primary key,
  categoria   text not null,
  nombre      text not null,
  descripcion text not null default '',
  precio      numeric(10,2) check (precio is null or precio >= 0),  -- null = «Precio por confirmar»
  imagen      text,                                                  -- ruta o URL de la foto
  nuevo       boolean not null default false,                        -- etiqueta NEW
  visible     boolean not null default true,                         -- false = oculto en la tienda
  orden       integer not null default 0,
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now()
);

create or replace function public.tocar_actualizado() returns trigger
language plpgsql set search_path = '' as $$
begin new.actualizado := now(); return new; end $$;

drop trigger if exists productos_actualizado on public.productos;
create trigger productos_actualizado before update on public.productos
for each row execute function public.tocar_actualizado();

-- ===== Admins: solo estos correos pueden modificar productos y fotos =====
create table if not exists public.admins (
  email text primary key
);

create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- ===== Seguridad (RLS) =====
alter table public.productos enable row level security;
alter table public.admins    enable row level security;

drop policy if exists "ver productos"      on public.productos;
drop policy if exists "crear productos"    on public.productos;
drop policy if exists "editar productos"   on public.productos;
drop policy if exists "borrar productos"   on public.productos;
drop policy if exists "verme como admin"   on public.admins;

-- Cualquiera ve los productos visibles; los admins ven también los ocultos.
create policy "ver productos" on public.productos for select
  to anon, authenticated using (visible or public.es_admin());
create policy "crear productos" on public.productos for insert
  to authenticated with check (public.es_admin());
create policy "editar productos" on public.productos for update
  to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "borrar productos" on public.productos for delete
  to authenticated using (public.es_admin());
-- Cada usuario solo puede comprobar si su propio correo es admin.
create policy "verme como admin" on public.admins for select
  to authenticated using (lower(email) = lower(coalesce(auth.jwt() ->> 'email', '')));

grant select on public.productos to anon, authenticated;
grant insert, update, delete on public.productos to authenticated;
grant usage, select on sequence public.productos_id_seq to authenticated;
grant select on public.admins to authenticated;
revoke all on function public.es_admin() from public;
grant execute on function public.es_admin() to anon, authenticated;

-- ===== Fotos (Storage) =====
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('productos', 'productos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "admins suben fotos"  on storage.objects;
drop policy if exists "admins editan fotos" on storage.objects;
drop policy if exists "admins borran fotos" on storage.objects;
drop policy if exists "admins ven fotos"    on storage.objects;

create policy "admins suben fotos" on storage.objects for insert
  to authenticated with check (bucket_id = 'productos' and public.es_admin());
create policy "admins editan fotos" on storage.objects for update
  to authenticated using (bucket_id = 'productos' and public.es_admin());
create policy "admins borran fotos" on storage.objects for delete
  to authenticated using (bucket_id = 'productos' and public.es_admin());
create policy "admins ven fotos" on storage.objects for select
  to authenticated using (bucket_id = 'productos' and public.es_admin());

